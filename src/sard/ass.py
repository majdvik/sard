"""ASS (Advanced SubStation Alpha) generation."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from . import __version__
from .bidi import repair
from .layout import Measurer, WrapOptions, wrap_text
from .subs import Cue

ASS_NEWLINE = r"\N"


@dataclass(frozen=True)
class AssOptions:
    play_res_x: int = 1920
    play_res_y: int = 1080
    font_name: str = "Arial"
    bold: bool = False
    font_size: int = 0  # 0 = derive from resolution
    primary_colour: str = "&H00FFFFFF"
    outline_colour: str = "&H00101010"
    back_colour: str = "&H80000000"
    outline: float = 3.0
    shadow: float = 1.0
    margin_lr: int = 60
    margin_v: int = 54
    max_lines: int = 2
    bidi: str = "marks"
    base: str = "auto"
    alignment: int = 2

    def resolved_font_size(self) -> int:
        if self.font_size:
            return int(self.font_size)
        return max(12, round(self.play_res_y * 0.0482))

    def text_width(self) -> float:
        return float(self.play_res_x - 2 * self.margin_lr)


def _ass_time(seconds: float) -> str:
    seconds = max(0.0, float(seconds))
    centiseconds = int(round(seconds * 100))
    hours, centiseconds = divmod(centiseconds, 360_000)
    minutes, centiseconds = divmod(centiseconds, 6_000)
    secs, cs = divmod(centiseconds, 100)
    return f"{hours}:{minutes:02d}:{secs:02d}.{cs:02d}"


def sanitize_text(text: str) -> str:
    """Remove ASS override syntax from user text (braces, backslashes)."""
    text = text.replace("\\", "/")
    return text.replace("{", "(").replace("}", ")").strip()


def build_ass(
    cues: Sequence[Cue],
    measurer: Measurer,
    options: AssOptions | None = None,
) -> str:
    """Build an ASS document with bidi repair and measured line wrapping."""
    options = options or AssOptions()
    size = options.resolved_font_size()
    wrap = WrapOptions(
        max_width=options.text_width(), max_lines=options.max_lines
    )
    bold = -1 if options.bold else 0
    header = [
        "[Script Info]",
        f"; Generated by sard {__version__}",
        "ScriptType: v4.00+",
        f"PlayResX: {options.play_res_x}",
        f"PlayResY: {options.play_res_y}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
        "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        (
            f"Style: Default,{options.font_name},{size},{options.primary_colour},"
            f"{options.primary_colour},{options.outline_colour},{options.back_colour},"
            f"{bold},0,0,0,100,100,0,0,1,{options.outline},{options.shadow},"
            f"{options.alignment},{options.margin_lr},{options.margin_lr},"
            f"{options.margin_v},1"
        ),
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    events: list[str] = []
    for cue in cues:
        result = repair(cue.text, base=options.base, mode=options.bidi)
        lines = wrap_text(result.text, measurer, wrap)
        text = ASS_NEWLINE.join(sanitize_text(line) for line in lines)
        events.append(
            f"Dialogue: 0,{_ass_time(cue.start)},{_ass_time(cue.end)},Default,,0,0,0,,"
            f"{{\\q2}}{text}"
        )
    return "\n".join(header + events) + "\n"
